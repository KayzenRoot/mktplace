#requires -Version 5.1
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$composeEnvironmentKeys = @(
    'APP_PORT'
    'MKTPLACE_DOCKER_INSTANCE_ID'
    'POSTGRES_DB'
    'POSTGRES_USER'
    'POSTGRES_PASSWORD'
    'TEST_POSTGRES_DB'
    'TEST_POSTGRES_USER'
    'TEST_POSTGRES_PASSWORD'
    'WATCHPACK_POLLING'
    'CHOKIDAR_USEPOLLING'
    'COMPOSE_PROFILES'
    'COMPOSE_PROJECT_NAME'
)
$previousComposeEnvironment = @{}
foreach ($key in $composeEnvironmentKeys) {
    $previousComposeEnvironment[$key] = [System.Environment]::GetEnvironmentVariable($key, 'Process')
}
$previousLockfileHash = [System.Environment]::GetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', 'Process')
Push-Location $repoRoot
try {
    $lockfileHash = (Get-FileHash -LiteralPath (Join-Path $repoRoot 'package-lock.json') -Algorithm SHA256).Hash.Substring(0, 12).ToLowerInvariant()
    [System.Environment]::SetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', $lockfileHash, 'Process')

    if (-not (Test-Path -LiteralPath '.env.docker.local')) {
        throw 'Missing .env.docker.local. Run .\scripts\dev-init.ps1 first.'
    }
    $instanceLines = @(Get-Content -LiteralPath '.env.docker.local' | Where-Object { $_ -match '^MKTPLACE_DOCKER_INSTANCE_ID=' })
    if ($instanceLines.Count -ne 1) { throw 'Expected one MKTPLACE_DOCKER_INSTANCE_ID in .env.docker.local; run dev-init.ps1.' }
    $instanceMatch = [regex]::Match([string]$instanceLines[0], '^MKTPLACE_DOCKER_INSTANCE_ID=([0-9a-f]{12})$')
    if (-not $instanceMatch.Success) { throw 'MKTPLACE_DOCKER_INSTANCE_ID must be the 12-character ID generated by dev-init.ps1.' }

    $composeInstanceId = $instanceMatch.Groups[1].Value
    foreach ($key in $composeEnvironmentKeys) { Remove-Item -LiteralPath ("Env:\" + $key) -ErrorAction SilentlyContinue }
    [System.Environment]::SetEnvironmentVariable('MKTPLACE_DOCKER_INSTANCE_ID', $composeInstanceId, 'Process')
    $composeProjectName = "mktplace-wo-blg001-$composeInstanceId"
    [System.Environment]::SetEnvironmentVariable('COMPOSE_PROJECT_NAME', $composeProjectName, 'Process')
    $composeArgs = @('-p', $composeProjectName, '-f', 'compose.dev.yaml', '--env-file', (Join-Path $repoRoot '.env.docker.local'))

    $migrationLines = @(
        'import { readFileSync } from "node:fs";'
        'import pg from "pg";'
        'const target = new URL(process.env.DATABASE_URL);'
        'if (target.hostname !== "postgres" || target.port !== "5432" || target.pathname !== "/mktplace_dev") {'
        '  throw new Error("Migration refused: expected the isolated mktplace_dev Compose database.");'
        '}'
        'const pool = new pg.Pool({ connectionString: target.toString() });'
        'try {'
        '  await pool.query(readFileSync("db/migrations/001_oauth_identity.sql", "utf8"));'
        '  const result = await pool.query("SELECT tablename FROM pg_tables WHERE schemaname = ''public'' ORDER BY tablename");'
        '  console.log("Migration applied. Public tables: " + result.rows.length);'
        '  for (const row of result.rows) console.log(row.tablename);'
        '} finally {'
        '  await pool.end();'
        '}'
    )
    $migrationCode = [string]::Join([System.Environment]::NewLine, $migrationLines)
    & docker compose @composeArgs run --build --rm app node --input-type=module -e $migrationCode
    if ($LASTEXITCODE -ne 0) { throw "Local migration failed with exit code $LASTEXITCODE." }
}
finally {
    if ($null -eq $previousLockfileHash) { Remove-Item -LiteralPath 'Env:\MKTPLACE_DEV_LOCKFILE_HASH' -ErrorAction SilentlyContinue }
    else { [System.Environment]::SetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', $previousLockfileHash, 'Process') }
    foreach ($key in $composeEnvironmentKeys) {
        $previousValue = $previousComposeEnvironment[$key]
        if ($null -eq $previousValue) { Remove-Item -LiteralPath ("Env:\" + $key) -ErrorAction SilentlyContinue }
        else { [System.Environment]::SetEnvironmentVariable($key, $previousValue, 'Process') }
    }
    Pop-Location
}
