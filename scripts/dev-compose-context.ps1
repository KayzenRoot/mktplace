# Shared setup and cleanup for the local Docker scripts.
Set-StrictMode -Version Latest

$script:DevComposeEnvironmentKeys = @(
    'APP_PORT'
    'MKTPLACE_DOCKER_INSTANCE_ID'
    'POSTGRES_DB'
    'POSTGRES_USER'
    'POSTGRES_PASSWORD'
    'TEST_POSTGRES_DB'
    'TEST_POSTGRES_USER'
    'TEST_POSTGRES_PASSWORD'
    'WATCHPACK_POLLING'
    'CHOKIDAR_USEPOLLING'
    'COMPOSE_PROFILES'
    'COMPOSE_PROJECT_NAME'
)

function Enter-DevComposeContext {
    param(
        [Parameter(Mandatory = $true)][string]$ScriptRoot,
        [string]$InstanceId,
        [switch]$TestProfile
    )

    $repoRoot = [System.IO.Path]::GetFullPath((Join-Path $ScriptRoot '..'))
    $previousEnvironment = @{}
    foreach ($key in $script:DevComposeEnvironmentKeys) {
        $previousEnvironment[$key] = [System.Environment]::GetEnvironmentVariable($key, 'Process')
    }
    $context = [pscustomobject]@{
        RepoRoot = $repoRoot
        ComposeArgs = @()
        PreviousEnvironment = $previousEnvironment
        PreviousLockfileHash = [System.Environment]::GetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', 'Process')
        LocationPushed = $false
        Restored = $false
    }

    Push-Location $repoRoot
    $context.LocationPushed = $true
    try {
        $lockfileHash = (Get-FileHash -LiteralPath (Join-Path $repoRoot 'package-lock.json') -Algorithm SHA256).Hash.Substring(0, 12).ToLowerInvariant()
        [System.Environment]::SetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', $lockfileHash, 'Process')

        $envFile = Join-Path $repoRoot '.env.docker.local'
        if (-not (Test-Path -LiteralPath $envFile)) {
            throw 'Missing .env.docker.local. Run .\scripts\dev-init.ps1 first.'
        }
        $instanceLines = @(Get-Content -LiteralPath $envFile | Where-Object { $_ -match '^MKTPLACE_DOCKER_INSTANCE_ID=' })
        if ($instanceLines.Count -ne 1) { throw 'Expected one MKTPLACE_DOCKER_INSTANCE_ID in .env.docker.local; run dev-init.ps1.' }
        $instanceMatch = [regex]::Match([string]$instanceLines[0], '^MKTPLACE_DOCKER_INSTANCE_ID=([0-9a-f]{12})$')
        if (-not $instanceMatch.Success) { throw 'MKTPLACE_DOCKER_INSTANCE_ID must be the 12-character ID generated by dev-init.ps1.' }

        if ([string]::IsNullOrWhiteSpace($InstanceId)) { $InstanceId = $instanceMatch.Groups[1].Value }
        if ($InstanceId -notmatch '^[0-9a-f]{12}$') { throw 'Compose instance ID must be 12 lowercase hexadecimal characters.' }

        foreach ($key in $script:DevComposeEnvironmentKeys) { Remove-Item -LiteralPath ("Env:\" + $key) -ErrorAction SilentlyContinue }
        [System.Environment]::SetEnvironmentVariable('MKTPLACE_DOCKER_INSTANCE_ID', $InstanceId, 'Process')
        $composeProjectName = "mktplace-wo-blg001-$InstanceId"
        [System.Environment]::SetEnvironmentVariable('COMPOSE_PROJECT_NAME', $composeProjectName, 'Process')

        $context.ComposeArgs = @('-p', $composeProjectName, '-f', 'compose.dev.yaml', '--env-file', $envFile)
        if ($TestProfile) { $context.ComposeArgs += @('--profile', 'test') }
        return $context
    }
    catch {
        Exit-DevComposeContext -Context $context
        throw
    }
}

function Exit-DevComposeContext {
    param([Parameter(Mandatory = $true)][psobject]$Context)

    if ($Context.Restored) { return }
    try {
        if ($null -eq $Context.PreviousLockfileHash) { Remove-Item -LiteralPath 'Env:\MKTPLACE_DEV_LOCKFILE_HASH' -ErrorAction SilentlyContinue }
        else { [System.Environment]::SetEnvironmentVariable('MKTPLACE_DEV_LOCKFILE_HASH', $Context.PreviousLockfileHash, 'Process') }
        foreach ($key in $script:DevComposeEnvironmentKeys) {
            $previousValue = $Context.PreviousEnvironment[$key]
            if ($null -eq $previousValue) { Remove-Item -LiteralPath ("Env:\" + $key) -ErrorAction SilentlyContinue }
            else { [System.Environment]::SetEnvironmentVariable($key, $previousValue, 'Process') }
        }
    }
    finally {
        if ($Context.LocationPushed) {
            Pop-Location
            $Context.LocationPushed = $false
        }
        $Context.Restored = $true
    }
}
